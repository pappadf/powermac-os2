"""gen-dma-patch.py FILE.DYN > dd-scsi-dma.S

A PReP bus master sees memory at $80000000 + physical, and OS/2's NCR driver
makes its bus addresses (SCRIPTS jump targets, table entries, data buffers)
by flipping bit 31: `xoris rA, rS, $8000`.  Bandit's bus masters see memory
at its physical address.  This writes an asm patch that turns every such
instruction in FILE into `mr rA, rS`.  (In DD_SCSI0/1.DYN every one of them is
a bus address: ncr_patch_scripts_program, the SCB, TID and global tables, the
command builders.)
"""
import os
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'remaster'))
import objpatch  # noqa: E402

data = open(sys.argv[1], 'rb').read()
elf = objpatch.Elf(data)
text = next(s for s in elf.secs if s['name'] == '.text')
print('/* SPDX-License-Identifier: GPL-2.0-only */')
print(f'/* Generated by tools/gen-dma-patch.py from {sys.argv[1].rsplit("/", 1)[-1]}: every `xoris rA, rS, $8000`. */')
n = 0
for off in range(0, text['size'], 4):
    w, = struct.unpack_from('<I', data, text['off'] + off)
    if w >> 26 == 27 and w & 0xFFFF == 0x8000:  # xoris
        rs, ra = (w >> 21) & 31, (w >> 16) & 31
        a = text['addr'] + off
        print(f'\t.section .patch.{a:#x}, "ax"\n\tmr    {ra}, {rs}')
        n += 1
print(f'/* {n} sites */')
